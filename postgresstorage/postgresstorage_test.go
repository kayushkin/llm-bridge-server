func TestInTransactionKeepsWorkThatSucceedsAndUndoesWorkThatFailsOrPanics(t *testing.T) {
	ctx := context.Background()
	notes := postgrestest.NewDatabase(t, notesModule).Open(notesModule)
	count := func() int {
		var rows int
		if err := notes.QueryRowContext(ctx, "SELECT count(*) FROM notes").Scan(&rows); err != nil {
			t.Fatal(err)
		}
		return rows
	}
	insert := func(tx *sql.Tx) error {
		_, err := tx.ExecContext(ctx, "INSERT INTO notes (title) VALUES ('x')")
		return err
	}

	if err := postgresstorage.InTransaction(ctx, notes, insert); err != nil {
		t.Fatal(err)
	}
	if count() != 1 {
		t.Fatalf("after work that succeeded there are %d rows, want 1", count())
	}

	refused := errors.New("refused")
	err := postgresstorage.InTransaction(ctx, notes, func(tx *sql.Tx) error {
		if err := insert(tx); err != nil {
			return err
		}
		return refused
	})
	if !errors.Is(err, refused) {
		t.Errorf("err = %v, want the work's own error back", err)
	}
	if count() != 1 {
		t.Errorf("after work that failed there are %d rows, want 1: its insert must be undone", count())
	}

	func() {
		defer func() {
			if recover() == nil {
				t.Error("the panic did not come back out of InTransaction")
			}
		}()
		postgresstorage.InTransaction(ctx, notes, func(tx *sql.Tx) error {
			insert(tx)
			panic("work panicked")
		})
	}()
	if count() != 1 {
		t.Errorf("after work that panicked there are %d rows, want 1: its insert must be undone", count())
	}
}

func TestMigrationsFromFilesReadsThemInOrderAndRefusesAStrayFile(t *testing.T) {
	files := fstest.MapFS{
		"migrations/0002_add_body.sql":     {Data: []byte("ALTER TABLE notes ADD COLUMN body text")},
		"migrations/0001_create_notes.sql": {Data: []byte("CREATE TABLE notes (title text)")},
	}
	migrations, err := postgresstorage.MigrationsFromFiles(files, "migrations")
	if err != nil {
		t.Fatal(err)
	}
	if len(migrations) != 2 || migrations[0].Version != 1 || migrations[0].Name != "create_notes" || migrations[1].Version != 2 || migrations[1].SQL != "ALTER TABLE notes ADD COLUMN body text" {
		t.Errorf("read %+v", migrations)
	}

	files["migrations/notes.txt"] = &fstest.MapFile{Data: []byte("not a migration")}
	if _, err := postgresstorage.MigrationsFromFiles(files, "migrations"); err == nil || !strings.Contains(err.Error(), "notes.txt") {
		t.Errorf("err = %v, want a refusal naming notes.txt", err)
	}

	skipping := fstest.MapFS{
		"migrations/0001_one.sql":   {Data: []byte("SELECT 1")},
		"migrations/0003_three.sql": {Data: []byte("SELECT 1")},
	}
	if _, err := postgresstorage.MigrationsFromFiles(skipping, "migrations"); err == nil {
		t.Error("a folder that skips version 2 was accepted")
	}
}

