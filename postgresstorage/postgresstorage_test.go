func TestAModuleCannotReadAnotherModulesTables(t *testing.T) {
	ctx := context.Background()
	database := postgrestest.NewDatabase(t, notesModule, ledgerModule)
	notes, ledger := database.Open(notesModule), database.Open(ledgerModule)

	if _, err := ledger.ExecContext(ctx, "INSERT INTO entries (amount) VALUES (100)"); err != nil {
		t.Fatalf("a module cannot write its own table: %v", err)
	}
	var amount int64
	err := notes.QueryRowContext(ctx, "SELECT amount FROM ledger.entries").Scan(&amount)
	if err == nil {
		t.Fatalf("the notes module read ledger.entries (%d); the database must refuse it", amount)
	}
	if !strings.Contains(err.Error(), "permission denied") {
		t.Errorf("err = %v, want a permission error from Postgres", err)
	}
	if _, err := notes.ExecContext(ctx, "INSERT INTO ledger.entries (amount) VALUES (1)"); err == nil {
		t.Error("the notes module wrote ledger.entries; the database must refuse it")
	}
}

func TestABareTableNameResolvesInTheModulesOwnSchemaOnly(t *testing.T) {
	ctx := context.Background()
	// Both modules act as the login itself here, so no role stands between
	// them: only the search path decides where a bare name is looked up. With
	// roles in place the wall would hide a search path that reached too far.
	notesWithoutRole, ledgerWithoutRole := notesModule, ledgerModule
	notesWithoutRole.Role, ledgerWithoutRole.Role = "", ""
	database := postgrestest.NewDatabase(t, notesWithoutRole, ledgerWithoutRole)
	notes := database.Open(notesWithoutRole)

	var schema string
	if err := notes.QueryRowContext(ctx, "SELECT table_schema FROM information_schema.tables WHERE table_name = 'notes'").Scan(&schema); err != nil {
		t.Fatal(err)
	}
	if schema != "notes" {
		t.Errorf("the notes table is in schema %q, want notes", schema)
	}
	// The ledger's table is there and this login may read it by its full name.
	if _, err := notes.ExecContext(ctx, "SELECT 1 FROM ledger.entries"); err != nil {
		t.Fatalf("with no roles the login reads ledger.entries by its full name: %v", err)
	}
	// Named bare from notes it must not be found.
	if _, err := notes.ExecContext(ctx, "SELECT 1 FROM entries"); err == nil || !strings.Contains(err.Error(), "does not exist") {
		t.Errorf("err = %v, want \"does not exist\": a bare name must not reach another module's table", err)
	}
}

