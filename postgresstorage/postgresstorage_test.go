func TestRecordIDsFormatAndParse(t *testing.T) {
	for number, want := range map[int64]string{1: "note_000001", 12: "note_000012", 999999: "note_999999", 1234567: "note_1234567"} {
		id := postgresstorage.FormatRecordID("note", number)
		if id != want {
			t.Errorf("FormatRecordID(note, %d) = %q, want %q", number, id, want)
		}
		back, err := postgresstorage.ParseRecordID("note", id)
		if err != nil || back != number {
			t.Errorf("ParseRecordID(note, %q) = %d, %v; want %d", id, back, err, number)
		}
	}
	for _, malformed := range []string{"", "note_", "note_12", "note_00001x", "note_-00001", "note_000000", "notebook_000001", "music_note_000001", "000001", "note_ 00001"} {
		if number, err := postgresstorage.ParseRecordID("note", malformed); err == nil {
			t.Errorf("ParseRecordID(note, %q) = %d, want an error", malformed, number)
		}
	}
	// A prefix that itself holds an underscore is read whole.
	if number, err := postgresstorage.ParseRecordID("music_note", "music_note_000004"); err != nil || number != 4 {
		t.Errorf("ParseRecordID(music_note, music_note_000004) = %d, %v; want 4", number, err)
	}
}

func TestContinueNumberingAfterKeepsEveryIDThatAlreadyExists(t *testing.T) {
	ctx := context.Background()
	notes := postgrestest.NewDatabase(t, notesModule).Open(notesModule)

	// Records copied in from the old database, with the numbers they had.
	err := postgresstorage.InTransaction(ctx, notes, func(tx *sql.Tx) error {
		if _, err := tx.ExecContext(ctx, "INSERT INTO notes (number, title) VALUES (3, 'old'), (41, 'old')"); err != nil {
			return err
		}
		// 57 was the old store's counter: note_000042 to note_000057 existed
		// once and were deleted, and their ids are still written in chats.
		return postgresstorage.ContinueNumberingAfter(ctx, tx, "notes", "number", 57)
	})
	if err != nil {
		t.Fatal(err)
	}
	var next int64
	if err := notes.QueryRowContext(ctx, "INSERT INTO notes (title) VALUES ('new') RETURNING number").Scan(&next); err != nil {
		t.Fatal(err)
	}
	if next != 58 {
		t.Errorf("the first new record is number %d, want 58", next)
	}
}

