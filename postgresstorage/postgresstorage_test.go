// Two made-up modules. notes numbers its records the way every store does.
var notesModule = postgresstorage.Module{
	Schema: "notes",
	Role:   "notes_module",
	Migrations: []postgresstorage.Migration{
		{Version: 1, Name: "create_notes", SQL: `CREATE TABLE notes (
			number bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			title  text NOT NULL
		)`},
		{Version: 2, Name: "add_body", SQL: `ALTER TABLE notes ADD COLUMN body text NOT NULL DEFAULT ''`},
	},
}

var ledgerModule = postgresstorage.Module{
	Schema: "ledger",
	Role:   "ledger_module",
	Migrations: []postgresstorage.Migration{
		{Version: 1, Name: "create_entries", SQL: `CREATE TABLE entries (
			number bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			amount bigint NOT NULL
		)`},
	},
}

func provisionedAndOpened(t *testing.T, database *postgrestest.Database, module postgresstorage.Module) *sql.DB {
	t.Helper()
	if err := postgresstorage.Provision(context.Background(), database.OpenAsAdministrator(), module); err != nil {
		t.Fatal(err)
	}
	return database.Open(module)
}

func appliedVersions(report postgresstorage.MigrationReport) []int {
	var versions []int
	for _, migration := range report.Applied {
		versions = append(versions, migration.Version)
	}
	return versions
}

func TestMigrateAppliesEachMigrationOnceInOrder(t *testing.T) {
	ctx := context.Background()
	db := provisionedAndOpened(t, postgrestest.NewDatabase(t), notesModule)

	report, err := postgresstorage.Migrate(ctx, db, notesModule)
	if err != nil {
		t.Fatal(err)
	}
	if got := appliedVersions(report); len(got) != 2 || got[0] != 1 || got[1] != 2 {
		t.Fatalf("first run applied %v, want [1 2]", got)
	}
	// The second migration's column exists, so both ran, and in order.
	if _, err := db.ExecContext(ctx, "INSERT INTO notes (title, body) VALUES ('a', 'b')"); err != nil {
		t.Fatalf("the migrated table does not take a row: %v", err)
	}

	again, err := postgresstorage.Migrate(ctx, db, notesModule)
	if err != nil {
		t.Fatal(err)
	}
	if len(again.Applied) != 0 {
		t.Errorf("second run applied %v, want nothing", appliedVersions(again))
	}

	var recorded int
	if err := db.QueryRowContext(ctx, "SELECT count(*) FROM schema_migrations").Scan(&recorded); err != nil {
		t.Fatal(err)
	}
	if recorded != 2 {
		t.Errorf("schema_migrations holds %d rows, want 2", recorded)
	}
}

func TestMigrateAppliesOnlyWhatALaterBinaryAdds(t *testing.T) {
	ctx := context.Background()
	db := provisionedAndOpened(t, postgrestest.NewDatabase(t), notesModule)

	older := notesModule
	older.Migrations = notesModule.Migrations[:1]
	if _, err := postgresstorage.Migrate(ctx, db, older); err != nil {
		t.Fatal(err)
	}
	report, err := postgresstorage.Migrate(ctx, db, notesModule)
	if err != nil {
		t.Fatal(err)
	}
	if got := appliedVersions(report); len(got) != 1 || got[0] != 2 {
		t.Errorf("the later binary applied %v, want [2]", got)
	}
}

func TestMigrateReportsVersionsNewerThanThisBinaryAndStillRuns(t *testing.T) {
	ctx := context.Background()
	db := provisionedAndOpened(t, postgrestest.NewDatabase(t), notesModule)
	if _, err := postgresstorage.Migrate(ctx, db, notesModule); err != nil {
		t.Fatal(err)
	}

	// The older server, started while the newer one is already live.
	older := notesModule
	older.Migrations = notesModule.Migrations[:1]
	report, err := postgresstorage.Migrate(ctx, db, older)
	if err != nil {
		t.Fatalf("an older binary must keep running beside a newer schema: %v", err)
	}
	if len(report.Applied) != 0 {
		t.Errorf("the older binary applied %v, want nothing", appliedVersions(report))
	}
	if len(report.NewerThanThisBinary) != 1 || report.NewerThanThisBinary[0] != 2 {
		t.Errorf("NewerThanThisBinary = %v, want [2]", report.NewerThanThisBinary)
	}
}

func TestMigrateRefusesAMigrationEditedAfterItRan(t *testing.T) {
	ctx := context.Background()
	db := provisionedAndOpened(t, postgrestest.NewDatabase(t), notesModule)
	if _, err := postgresstorage.Migrate(ctx, db, notesModule); err != nil {
		t.Fatal(err)
	}

	edited := notesModule
	edited.Migrations = []postgresstorage.Migration{
		notesModule.Migrations[0],
		{Version: 2, Name: "add_body", SQL: `ALTER TABLE notes ADD COLUMN body text NOT NULL DEFAULT 'changed'`},
	}
	_, err := postgresstorage.Migrate(ctx, db, edited)
	if !errors.Is(err, postgresstorage.ErrMigrationEdited) {
		t.Fatalf("err = %v, want ErrMigrationEdited", err)
	}
	if !strings.Contains(err.Error(), "migration 2 (add_body)") {
		t.Errorf("the error %q does not name the edited migration", err)
	}
}

func TestMigrateLeavesNoTraceOfAMigrationThatFails(t *testing.T) {
	ctx := context.Background()
	db := provisionedAndOpened(t, postgrestest.NewDatabase(t), notesModule)

	broken := notesModule
	broken.Migrations = []postgresstorage.Migration{
		notesModule.Migrations[0],
		{Version: 2, Name: "half_done", SQL: `CREATE TABLE left_behind (n integer); SELECT no_such_function()`},
	}
	report, err := postgresstorage.Migrate(ctx, db, broken)
	if err == nil {
		t.Fatal("a migration that fails must fail Migrate")
	}
	if got := appliedVersions(report); len(got) != 1 || got[0] != 1 {
		t.Errorf("the report says %v were applied, want [1]: the one before the failure", got)
	}
	var leftBehind bool
	if err := db.QueryRowContext(ctx, "SELECT to_regclass('notes.left_behind') IS NOT NULL").Scan(&leftBehind); err != nil {
		t.Fatal(err)
	}
	if leftBehind {
		t.Error("the failed migration's first statement was kept; it must roll back whole")
	}
	// Fixed, it runs: nothing recorded the failed try.
	if _, err := postgresstorage.Migrate(ctx, db, notesModule); err != nil {
		t.Fatalf("the corrected migration did not run after the failure: %v", err)
	}
}

func TestMigrateRunsEachMigrationOnceWhenServersStartTogether(t *testing.T) {
	ctx := context.Background()
	database := postgrestest.NewDatabase(t)
	if err := postgresstorage.Provision(ctx, database.OpenAsAdministrator(), notesModule); err != nil {
		t.Fatal(err)
	}

	const servers = 8
	var wait sync.WaitGroup
	applied := make([]int, servers)
	errs := make([]error, servers)
	for index := range servers {
		db := database.Open(notesModule) // each server has a pool of its own
		wait.Add(1)
		go func() {
			defer wait.Done()
			report, err := postgresstorage.Migrate(ctx, db, notesModule)
			applied[index], errs[index] = len(report.Applied), err
		}()
	}
	wait.Wait()

	total := 0
	for index := range servers {
		if errs[index] != nil {
			t.Errorf("server %d: %v", index, errs[index])
		}
		total += applied[index]
	}
	if total != len(notesModule.Migrations) {
		t.Errorf("the servers applied %d migrations between them, want %d: each exactly once", total, len(notesModule.Migrations))
	}
}

