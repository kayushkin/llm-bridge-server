package postgresstorage_test

import (
	"context"
	"testing"

	"github.com/kayushkin/llm-bridge-server/postgresstorage"
	"github.com/kayushkin/llm-bridge-server/postgresstorage/postgrestest"
)

// shelvesModule keeps rows a row-level security policy narrows to the owner
// its pool names, as a connected records store does.
var shelvesModule = postgresstorage.Module{
	Schema: "shelves",
	Role:   "shelves_module",
	Migrations: []postgresstorage.Migration{
		{Version: 1, Name: "create_shelves", SQL: `CREATE TABLE shelves (
			number bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			owner  text NOT NULL DEFAULT current_setting('shelves.owner')
		);
		ALTER TABLE shelves ENABLE ROW LEVEL SECURITY;
		ALTER TABLE shelves FORCE ROW LEVEL SECURITY;
		CREATE POLICY own_shelves ON shelves USING (owner = current_setting('shelves.owner', true))`},
	},
}

func TestASessionSettingReachesEveryConnectionOfItsPool(t *testing.T) {
	ctx := context.Background()
	database := postgrestest.NewDatabase(t)
	if err := postgresstorage.Provision(ctx, database.OpenAsAdministrator(), shelvesModule); err != nil {
		t.Fatal(err)
	}
	if _, err := postgresstorage.Migrate(ctx, database.Open(shelvesModule), shelvesModule); err != nil {
		t.Fatal(err)
	}
	pools := map[string]int{"owner_a": 2, "owner_b": 1}
	for owner, shelves := range pools {
		db, err := postgresstorage.OpenWithSessionSettings(ctx, database.URL(), shelvesModule, map[string]string{"shelves.owner": owner})
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { db.Close() })
		for range shelves {
			if _, err := db.ExecContext(ctx, `INSERT INTO shelves DEFAULT VALUES`); err != nil {
				t.Fatal(err)
			}
		}
	}
	for owner, shelves := range pools {
		db, err := postgresstorage.OpenWithSessionSettings(ctx, database.URL(), shelvesModule, map[string]string{"shelves.owner": owner})
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { db.Close() })
		var count int
		if err := db.QueryRowContext(ctx, `SELECT count(*) FROM shelves`).Scan(&count); err != nil {
			t.Fatal(err)
		}
		if count != shelves {
			t.Fatalf("%s sees %d shelves, want its own %d", owner, count, shelves)
		}
	}
	if _, err := postgresstorage.OpenWithSessionSettings(ctx, database.URL(), shelvesModule, map[string]string{"other.owner": "x"}); err == nil {
		t.Fatal("a setting named after another module's schema must be refused")
	}
}
