-- possession-store: the things one owner owns, by kind, with outfits,
-- products, purchases and the two-reader photo review. Times are epoch
-- seconds, money integer cents with a currency, lists and nested records JSON
-- text, as the API has always served them. Text sorts and compares byte by
-- byte (COLLATE "C"), as it did in SQLite.
--
-- A record's public id is its type's prefix and its number: possession_000001,
-- garment_000001, outfit_000001 and the rest. Both are stored, the number in
-- seq, an identity Postgres hands out once, and the id, checked to be the
-- prefix and that number, because every query of the store names records by
-- their id.
--
-- Every row carries owner_principal_id, principal-store's id of the person who
-- keeps it. A row a session writes takes the owner its connection names
-- (possessions.owner_principal_id), and row-level security shows a connection
-- only that owner's rows, or every owner's when it names
-- possessions.every_owner = on, which only reads. A child row's foreign key
-- runs over (owner_principal_id, parent id), so it can never hang on another
-- owner's record, and every uniqueness rule on something the owner names is
-- per owner. Foreign keys are DEFERRABLE, and checked at each statement as
-- usual, so that an import can copy rows that point at one another
-- (a possession merged into a later one) in one transaction.

-- record_id is the public id of record number of the type prefix names.
CREATE FUNCTION record_id(prefix text, number bigint) RETURNS text
    LANGUAGE sql IMMUTABLE STRICT
    RETURN prefix || '_' || CASE WHEN number < 1000000 THEN lpad(number::text, 6, '0') ELSE number::text END;

-- owner_in_reach says whether this connection may read a row owner keeps.
CREATE FUNCTION owner_in_reach(owner text) RETURNS boolean
    LANGUAGE sql STABLE
    RETURN coalesce(current_setting('possessions.every_owner', true), '') = 'on'
        OR owner = current_setting('possessions.owner_principal_id', true);

-- json_array_texts is every string in a JSON array kept as text, and nothing
-- for a document that is not an array (null among them), as SQLite's
-- json_each answered.
CREATE FUNCTION json_array_texts(document text) RETURNS SETOF text
    LANGUAGE sql IMMUTABLE
    AS $$ SELECT jsonb_array_elements_text(CASE WHEN jsonb_typeof(document::jsonb) = 'array' THEN document::jsonb ELSE '[]'::jsonb END) $$;

-- json_array_items is every item of a JSON array kept as text, the same way.
CREATE FUNCTION json_array_items(document text) RETURNS SETOF jsonb
    LANGUAGE sql IMMUTABLE
    AS $$ SELECT jsonb_array_elements(CASE WHEN jsonb_typeof(document::jsonb) = 'array' THEN document::jsonb ELSE '[]'::jsonb END) $$;

-- owner_written says whether this connection may write a row owner keeps.
CREATE FUNCTION owner_written(owner text) RETURNS boolean
    LANGUAGE sql STABLE
    RETURN owner = current_setting('possessions.owner_principal_id', true);

-- What every owned thing has, whatever kind it is. A kind (garment, computer...)
-- is a table of its own holding only that kind's facts, one row per
-- possession, with its own id prefix.
CREATE TABLE possessions (
    id text COLLATE "C" PRIMARY KEY,
    seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id text COLLATE "C" NOT NULL DEFAULT current_setting('possessions.owner_principal_id') CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    name text COLLATE "C" NOT NULL,
    brand text COLLATE "C" NOT NULL DEFAULT '',
    model text COLLATE "C" NOT NULL DEFAULT '',
    serial_number text COLLATE "C" NOT NULL DEFAULT '',
    description text COLLATE "C" NOT NULL DEFAULT '',
    quantity bigint NOT NULL DEFAULT 1,
    condition text COLLATE "C" NOT NULL DEFAULT '',
    status text COLLATE "C" NOT NULL,
    place_id text COLLATE "C",
    spot text COLLATE "C" NOT NULL DEFAULT '',
    acquired_at bigint NOT NULL DEFAULT 0,
    acquired_how text COLLATE "C" NOT NULL DEFAULT '',
    purchase_line_id text COLLATE "C",
    price_cents bigint,
    price_currency text COLLATE "C" NOT NULL DEFAULT '',
    disposed_at bigint NOT NULL DEFAULT 0,
    tags text COLLATE "C" NOT NULL DEFAULT '[]',
    created_by text COLLATE "C" NOT NULL,
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    deleted_at bigint NOT NULL DEFAULT 0,
    merged_into_id text COLLATE "C",
    room text COLLATE "C" NOT NULL DEFAULT '',
    product_id text COLLATE "C",
    budget_transaction_id text COLLATE "C",
    CHECK (id = record_id('possession', seq)),
    UNIQUE (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, merged_into_id) REFERENCES possessions (owner_principal_id, id) DEFERRABLE
);
CREATE INDEX possessions_status_index ON possessions (owner_principal_id, deleted_at, status);
CREATE INDEX possessions_place_index ON possessions (place_id);
CREATE INDEX possessions_product_index ON possessions (product_id);
ALTER TABLE possessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE possessions FORCE ROW LEVEL SECURITY;
CREATE POLICY owner_reach ON possessions USING (owner_in_reach(owner_principal_id)) WITH CHECK (owner_written(owner_principal_id));

