-- location-store: where one person has been. Named places, visits to them,
-- trips between them, the raw location points underneath, the imports that
-- brought them in, and what the passes over them found (home periods,
-- calendar event links, recurring-series places, place name suggestions).
-- Times are epoch seconds, 0 meaning unset, as the API has always served
-- them. Coordinates are double precision, as SQLite's REAL was.
--
-- Every row carries owner_principal_id, principal-store's id of the person
-- who keeps it. A child or linked row carries the owner of what it belongs
-- to, and its foreign key runs over (owner_principal_id, parent id), so a
-- visit at another owner's place, a trip inside another owner's trip, a point
-- in another owner's import or a link to another owner's visit cannot be
-- written. Every uniqueness rule is per owner: two people may each import the
-- same file or know the same Google place.
--
-- A record's public id is its type's prefix and its number (place_000001).
-- Records point at each other by those ids, in plain columns and in columns
-- that name one of several types (a revision's entity_id, a calendar link's
-- target_id), so the id is stored beside the number, and a CHECK holds it to
-- the number: the store writes the id with postgresstorage.FormatRecordID and
-- record_id below says the same thing in SQL.
--
-- Nothing a person can cite is hard-deleted: DELETE stamps deleted_at, and
-- every update, import change, delete and restore of a place, visit or trip
-- first copies the whole record into revisions.

CREATE FUNCTION record_id(prefix text, number bigint) RETURNS text
    LANGUAGE sql IMMUTABLE STRICT
    RETURN prefix || '_' || CASE WHEN number < 1000000 THEN lpad(number::text, 6, '0') ELSE number::text END;

-- One imported file, found again among its owner's imports by its hash:
-- importing the same file twice changes nothing. finished_at is 0 while an
-- import is still sending; running the importer again on the same file
-- resumes it.
CREATE TABLE imports (
    id                 text PRIMARY KEY,                -- import_000001
    seq                bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    kind               text NOT NULL,                   -- vocabulary.go ImportKinds
    sha256             text NOT NULL,                   -- of the file (or of the records, for a photo-store import)
    source_machine     text NOT NULL DEFAULT '',        -- where the file was read
    source_path        text NOT NULL DEFAULT '',        -- its path there
    imported_at        bigint NOT NULL,
    finished_at        bigint NOT NULL DEFAULT 0,
    counts             text NOT NULL DEFAULT '{}',      -- ImportCounts as JSON, summed over every batch
    snapshot           text,                            -- ImportSnapshot as JSON; NULL unless a full snapshot
    snapshot_changes   text,                            -- SnapshotChanges as JSON; NULL until a reconcile ran
    recorded_by        text NOT NULL DEFAULT '',        -- who sent a live import's points
    CHECK (id = record_id('import', seq)),
    UNIQUE (owner_principal_id, id),
    UNIQUE (owner_principal_id, sha256)
);

-- A named spot.
CREATE TABLE places (
    id                   text PRIMARY KEY,              -- place_000001
    seq                  bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id   text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    name                 text NOT NULL DEFAULT '',
    latitude             double precision NOT NULL,
    longitude            double precision NOT NULL,
    radius_meters        double precision NOT NULL DEFAULT 0,  -- 0 = not given
    address              text NOT NULL DEFAULT '',
    kind                 text NOT NULL,                 -- vocabulary.go PlaceKinds
    google_place_id      text,                          -- NULL when no source gave one; an import finds the place again by it
    description          text NOT NULL DEFAULT '',
    described_by         text NOT NULL DEFAULT '',
    tags                 jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(tags) = 'array'),
    source               text NOT NULL,                 -- vocabulary.go RecordSources
    import_id            text,                          -- the import that created it; NULL when made by hand
    locality             text,                          -- Locality as JSON; NULL until named
    created_at           bigint NOT NULL,
    updated_at           bigint NOT NULL,
    deleted_at           bigint NOT NULL DEFAULT 0,
    merged_into_place_id text,                          -- the place this one was merged into
    CHECK (id = record_id('place', seq)),
    UNIQUE (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, import_id) REFERENCES imports (owner_principal_id, id),
    -- Deferrable so a copy of a standalone store can write a place before
    -- the later one it was merged into.
    FOREIGN KEY (owner_principal_id, merged_into_place_id) REFERENCES places (owner_principal_id, id) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE UNIQUE INDEX places_google_index ON places (owner_principal_id, google_place_id) WHERE google_place_id IS NOT NULL;
CREATE INDEX places_kind_index ON places (owner_principal_id, deleted_at, kind);
CREATE INDEX places_merged_into_index ON places (merged_into_place_id) WHERE merged_into_place_id IS NOT NULL;
CREATE INDEX places_coordinate_index ON places (owner_principal_id, latitude, longitude);
CREATE INDEX places_tags_index ON places USING gin (tags jsonb_path_ops);

-- Being somewhere from started_at to ended_at.
CREATE TABLE visits (
    id                      text PRIMARY KEY,           -- visit_000001
    seq                     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id      text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    place_id                text,
    started_at              bigint NOT NULL,
    ended_at                bigint NOT NULL,
    latitude                double precision,
    longitude               double precision,
    probability             double precision,           -- 0..1, how sure the source is of the place; NULL when it gave none
    source_semantic_type    text NOT NULL DEFAULT '',   -- the source's own word for the place (HOME, TYPE_WORK…)
    description             text NOT NULL DEFAULT '',
    described_by            text NOT NULL DEFAULT '',
    tags                    jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(tags) = 'array'),
    source                  text NOT NULL,
    source_ref              text NOT NULL DEFAULT '',   -- what an import finds the visit again by; '' when made by hand
    import_id               text,
    locality                text,                       -- Locality as JSON; NULL until named
    superseded_by_import_id text,                       -- the newer export that no longer holds it
    created_at              bigint NOT NULL,
    updated_at              bigint NOT NULL,
    deleted_at              bigint NOT NULL DEFAULT 0,
    CHECK (id = record_id('visit', seq)),
    UNIQUE (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, place_id) REFERENCES places (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, import_id) REFERENCES imports (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, superseded_by_import_id) REFERENCES imports (owner_principal_id, id)
);
CREATE UNIQUE INDEX visits_source_ref_index ON visits (owner_principal_id, source, source_ref) WHERE source_ref <> '';
CREATE INDEX visits_time_index ON visits (owner_principal_id, deleted_at, started_at, seq);
CREATE INDEX visits_place_index ON visits (place_id, started_at);
CREATE INDEX visits_tags_index ON visits USING gin (tags jsonb_path_ops);

-- A movement, or a journey made of them. parent_trip_id groups the drives of
-- a road trip or a holiday under one trip; an import never sets it.
CREATE TABLE trips (
    id                      text PRIMARY KEY,           -- trip_000001
    seq                     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id      text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    kind                    text NOT NULL DEFAULT 'movement',  -- vocabulary.go TripKinds
    parent_trip_id          text,
    parent_set_by           text NOT NULL DEFAULT '',   -- who set or cleared parent_trip_id
    started_at              bigint NOT NULL,
    ended_at                bigint NOT NULL,
    start_latitude          double precision,
    start_longitude         double precision,
    end_latitude            double precision,
    end_longitude           double precision,
    start_place_id          text,
    end_place_id            text,
    mode                    text NOT NULL,              -- vocabulary.go TripModes
    source_mode             text NOT NULL DEFAULT '',   -- the source's own word (IN_PASSENGER_VEHICLE)
    distance_meters         double precision,
    probability             double precision,           -- 0..1, how sure the source is of the mode
    title                   text NOT NULL DEFAULT '',
    title_by                text NOT NULL DEFAULT '',   -- who wrote the title
    description             text NOT NULL DEFAULT '',
    described_by            text NOT NULL DEFAULT '',
    tags                    jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(tags) = 'array'),
    source                  text NOT NULL,
    source_ref              text NOT NULL DEFAULT '',
    import_id               text,
    start_locality          text,                       -- Locality as JSON; NULL until named
    end_locality            text,
    superseded_by_import_id text,
    created_at              bigint NOT NULL,
    updated_at              bigint NOT NULL,
    deleted_at              bigint NOT NULL DEFAULT 0,
    CHECK (id = record_id('trip', seq)),
    UNIQUE (owner_principal_id, id),
    -- Deferrable so a copy of a standalone store can write a movement before
    -- the later journey it is part of.
    FOREIGN KEY (owner_principal_id, parent_trip_id) REFERENCES trips (owner_principal_id, id) DEFERRABLE INITIALLY IMMEDIATE,
    FOREIGN KEY (owner_principal_id, start_place_id) REFERENCES places (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, end_place_id) REFERENCES places (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, import_id) REFERENCES imports (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, superseded_by_import_id) REFERENCES imports (owner_principal_id, id)
);
CREATE UNIQUE INDEX trips_source_ref_index ON trips (owner_principal_id, source, source_ref) WHERE source_ref <> '';
CREATE INDEX trips_time_index ON trips (owner_principal_id, deleted_at, started_at, seq);
CREATE INDEX trips_parent_index ON trips (parent_trip_id, started_at);
CREATE INDEX trips_kind_index ON trips (owner_principal_id, kind, deleted_at, started_at);
CREATE INDEX trips_start_place_index ON trips (start_place_id) WHERE start_place_id IS NOT NULL;
CREATE INDEX trips_end_place_index ON trips (end_place_id) WHERE end_place_id IS NOT NULL;
CREATE INDEX trips_tags_index ON trips USING gin (tags jsonb_path_ops);

-- A trip's path, in order. An import replaces it whole when the trip changes.
CREATE TABLE trip_path_points (
    owner_principal_id text NOT NULL,
    trip_id            text NOT NULL,
    position           integer NOT NULL,
    latitude           double precision NOT NULL,
    longitude          double precision NOT NULL,
    timestamp          bigint,                          -- NULL when the source gives the point no time
    PRIMARY KEY (trip_id, position),
    FOREIGN KEY (owner_principal_id, trip_id) REFERENCES trips (owner_principal_id, id)
);

-- Raw location fixes; there may be millions. No public ids: a point is read
-- by time, and seq keeps the order they were written in, as SQLite's rowid
-- did. The unique index both serves an owner's time ranges and makes a second
-- copy of a fix from the same source a no-op. A point with a source_ref (a
-- photo id) replaces any earlier point of the owner's with the same source
-- and source_ref.
CREATE TABLE points (
    seq                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    owner_principal_id text NOT NULL,
    timestamp          bigint NOT NULL,
    latitude           double precision NOT NULL,
    longitude          double precision NOT NULL,
    accuracy_meters    double precision,
    source             text NOT NULL,                   -- vocabulary.go PointSources
    source_ref         text NOT NULL DEFAULT '',
    import_id          text NOT NULL,
    FOREIGN KEY (owner_principal_id, import_id) REFERENCES imports (owner_principal_id, id)
);
CREATE UNIQUE INDEX points_identity_index ON points (owner_principal_id, timestamp, latitude, longitude, source);
CREATE INDEX points_source_ref_index ON points (owner_principal_id, source, source_ref) WHERE source_ref <> '';
CREATE INDEX points_source_time_index ON points (owner_principal_id, source, timestamp);
CREATE INDEX points_import_index ON points (import_id);

-- The whole record as GET answered it, just before each change. entity_id
-- names a place, visit or trip; the generated columns split it by type so
-- each gets a foreign key that holds it to the revision's owner.
CREATE TABLE revisions (
    revision_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    owner_principal_id text NOT NULL,
    entity_type        text NOT NULL CHECK (entity_type IN ('place', 'visit', 'trip')),
    entity_id          text NOT NULL,
    reason             text NOT NULL,                   -- update | import | delete | restore | attach | …
    replaced_at        bigint NOT NULL,
    row_json           text NOT NULL,                   -- the whole row as it was, as JSON
    place_id           text GENERATED ALWAYS AS (CASE WHEN entity_type = 'place' THEN entity_id END) STORED,
    visit_id           text GENERATED ALWAYS AS (CASE WHEN entity_type = 'visit' THEN entity_id END) STORED,
    trip_id            text GENERATED ALWAYS AS (CASE WHEN entity_type = 'trip' THEN entity_id END) STORED,
    FOREIGN KEY (owner_principal_id, place_id) REFERENCES places (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, visit_id) REFERENCES visits (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, trip_id) REFERENCES trips (owner_principal_id, id)
);
CREATE INDEX revisions_entity_index ON revisions (entity_id, revision_id DESC);
CREATE INDEX revisions_owner_index ON revisions (owner_principal_id);

-- A stretch of time with one home base: the place the user slept most
-- nights. location-group-journeys writes these from the visits, and a re-run
-- updates the ones it wrote. ended_at 0 runs on past the newest data.
CREATE TABLE home_periods (
    id                 text PRIMARY KEY,                -- home_period_000001
    seq                bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    place_id           text,                            -- NULL when the nights there named no place
    latitude           double precision NOT NULL,
    longitude          double precision NOT NULL,
    locality           text,                            -- Locality as JSON; NULL until named
    started_at         bigint NOT NULL,
    ended_at           bigint NOT NULL DEFAULT 0,
    nights_known       integer NOT NULL DEFAULT 0,
    nights_at_home     integer NOT NULL DEFAULT 0,
    described_by       text NOT NULL,                   -- who found it: location-group-journeys
    created_at         bigint NOT NULL,
    updated_at         bigint NOT NULL,
    deleted_at         bigint NOT NULL DEFAULT 0,
    CHECK (id = record_id('home_period', seq)),
    UNIQUE (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, place_id) REFERENCES places (owner_principal_id, id)
);
CREATE INDEX home_periods_time_index ON home_periods (owner_principal_id, deleted_at, started_at);
CREATE INDEX home_periods_place_index ON home_periods (place_id) WHERE place_id IS NOT NULL;

-- Which visits and trips each import's file holds, whether the import made
-- them, changed them or found them as they were. A full-snapshot export
-- supersedes what an older one of the same owner held in its span and it
-- does not.
CREATE TABLE import_records (
    owner_principal_id text NOT NULL,
    import_id          text NOT NULL,
    entity_type        text NOT NULL CHECK (entity_type IN ('visit', 'trip')),
    entity_id          text NOT NULL,
    visit_id           text GENERATED ALWAYS AS (CASE WHEN entity_type = 'visit' THEN entity_id END) STORED,
    trip_id            text GENERATED ALWAYS AS (CASE WHEN entity_type = 'trip' THEN entity_id END) STORED,
    PRIMARY KEY (import_id, entity_type, entity_id),
    FOREIGN KEY (owner_principal_id, import_id) REFERENCES imports (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, visit_id) REFERENCES visits (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, trip_id) REFERENCES trips (owner_principal_id, id)
);
CREATE INDEX import_records_entity_index ON import_records (entity_id);

-- A calendar event tied to where the user was for it. The event is Google
-- Calendar's, found again by calendar_id and event_id; summary and location
-- are carried for display only and never read back to find anything.
-- location-match-calendar rewrites only links whose matched_by is its own,
-- and never makes again a link a person deleted (deleted_by 'hand').
CREATE TABLE calendar_event_links (
    id                 text PRIMARY KEY,                -- calendar_event_link_000001
    seq                bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    calendar_id        text NOT NULL,
    event_id           text NOT NULL,
    recurring_event_id text NOT NULL DEFAULT '',
    summary            text NOT NULL DEFAULT '',
    location           text NOT NULL DEFAULT '',
    started_at         bigint NOT NULL,
    ended_at           bigint NOT NULL,
    all_day            boolean NOT NULL DEFAULT false,
    target_type        text NOT NULL CHECK (target_type IN ('visit', 'trip', 'place')),
    target_id          text NOT NULL,
    rule               text NOT NULL,                   -- vocabulary.go CalendarMatchRules
    confidence         double precision NOT NULL,
    reason             text NOT NULL DEFAULT '',
    matched_by         text NOT NULL,                   -- location-match-calendar | hand
    created_at         bigint NOT NULL,
    updated_at         bigint NOT NULL,
    deleted_at         bigint NOT NULL DEFAULT 0,
    deleted_by         text NOT NULL DEFAULT '',
    target_visit_id    text GENERATED ALWAYS AS (CASE WHEN target_type = 'visit' THEN target_id END) STORED,
    target_trip_id     text GENERATED ALWAYS AS (CASE WHEN target_type = 'trip' THEN target_id END) STORED,
    target_place_id    text GENERATED ALWAYS AS (CASE WHEN target_type = 'place' THEN target_id END) STORED,
    CHECK (id = record_id('calendar_event_link', seq)),
    UNIQUE (owner_principal_id, id),
    UNIQUE (owner_principal_id, calendar_id, event_id, target_type, target_id),
    FOREIGN KEY (owner_principal_id, target_visit_id) REFERENCES visits (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, target_trip_id) REFERENCES trips (owner_principal_id, id),
    FOREIGN KEY (owner_principal_id, target_place_id) REFERENCES places (owner_principal_id, id)
);
CREATE INDEX calendar_event_links_target_index ON calendar_event_links (target_id, deleted_at);
CREATE INDEX calendar_event_links_time_index ON calendar_event_links (owner_principal_id, deleted_at, started_at);
CREATE INDEX calendar_event_links_calendar_index ON calendar_event_links (owner_principal_id, calendar_id, started_at);

-- What location-match-calendar found for each recurring series with no
-- location: the spot the user was at for most of its times they were out,
-- how many times agreed, and whether that was enough to link. One row per
-- owner and series, rewritten by each run that reads it. place_id is the
-- leading spot's place even when the outcome is not linked, so a person can
-- see how near it came.
CREATE TABLE calendar_series_places (
    id                 text PRIMARY KEY,                -- calendar_series_place_000001
    seq                bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    calendar_id        text NOT NULL,
    recurring_event_id text NOT NULL,
    summary            text NOT NULL DEFAULT '',        -- for display only
    place_id           text,
    spot_place_ids     jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(spot_place_ids) = 'array'),  -- the places within reach of place_id that count as the same spot
    instances          integer NOT NULL,                -- timed times of the series in the window read
    instances_out      integer NOT NULL,                -- of those, times the user was at a place out of home, not away
    instances_at_place integer NOT NULL,                -- of those, times at the spot
    agreement          double precision NOT NULL,       -- instances_at_place / instances_out, 0 when none
    confidence         double precision NOT NULL,       -- what the links carry; 0 unless linked
    outcome            text NOT NULL,                   -- vocabulary.go SeriesOutcomes
    first_instance_at  bigint NOT NULL,
    last_instance_at   bigint NOT NULL,
    window_from        bigint NOT NULL,                 -- the run's window
    window_to          bigint NOT NULL,
    matched_by         text NOT NULL,                   -- location-match-calendar
    created_at         bigint NOT NULL,
    updated_at         bigint NOT NULL,
    CHECK (id = record_id('calendar_series_place', seq)),
    UNIQUE (owner_principal_id, id),
    UNIQUE (owner_principal_id, calendar_id, recurring_event_id),
    FOREIGN KEY (owner_principal_id, place_id) REFERENCES places (owner_principal_id, id)
);
CREATE INDEX calendar_series_places_place_index ON calendar_series_places (place_id);
CREATE INDEX calendar_series_places_spot_index ON calendar_series_places USING gin (spot_place_ids jsonb_path_ops);

-- A name a place might have, found offline by location-suggest-place-names.
-- Never applied by a run: accepting one through the routes names the place.
-- A run rewrites only proposed ones, and deletes proposed ones it no longer
-- finds; accepted and rejected ones stay as decided.
CREATE TABLE place_suggestions (
    id                 text PRIMARY KEY,                -- place_suggestion_000001
    seq                bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_principal_id text NOT NULL CHECK (owner_principal_id ~ '^principal_[0-9]{6,}$'),
    place_id           text NOT NULL,
    source             text NOT NULL,                   -- vocabulary.go PlaceSuggestionSources
    source_ref         text NOT NULL,                   -- node/123, way/456, calendar:node/789
    name               text NOT NULL DEFAULT '',
    address            text NOT NULL DEFAULT '',
    kind               text NOT NULL DEFAULT '',        -- '' leaves the place's kind alone
    distance_meters    double precision NOT NULL DEFAULT 0,
    reason             text NOT NULL DEFAULT '',
    evidence           text NOT NULL DEFAULT '{}',      -- PlaceSuggestionEvidence as JSON
    status             text NOT NULL,                   -- proposed | accepted | rejected
    proposed_by        text NOT NULL,
    decided_by         text NOT NULL DEFAULT '',
    decided_at         bigint NOT NULL DEFAULT 0,
    decision_note      text NOT NULL DEFAULT '',
    created_at         bigint NOT NULL,
    updated_at         bigint NOT NULL,
    deleted_at         bigint NOT NULL DEFAULT 0,
    CHECK (id = record_id('place_suggestion', seq)),
    UNIQUE (owner_principal_id, id),
    UNIQUE (owner_principal_id, place_id, source, source_ref),
    FOREIGN KEY (owner_principal_id, place_id) REFERENCES places (owner_principal_id, id)
);
CREATE INDEX place_suggestions_status_index ON place_suggestions (owner_principal_id, status, deleted_at);
