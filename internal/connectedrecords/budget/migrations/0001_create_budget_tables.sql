-- budget-store: one person's books, kept by double entry.
--
-- A transaction holds two or more postings whose amounts sum to zero. A
-- posting lands on an account (money held or owed) or a category (where money
-- came from or went). Amounts are integer cents (bigint), USD only: money is
-- never a floating point number here.
--
-- Sign: a posting on an account is the change in that account's balance. An
-- asset's balance is positive; a debt's balance is negative, so a card
-- purchase is a negative posting on the card and paying the card is positive.
-- A category posting is the other side: spending is positive on an expense
-- category, income is negative on an income category.
--
-- Owners. Every row carries owner_principal_id, principal-store's id of the
-- person whose books it is in. Each person has their own ledger: their own
-- accounts, categories (with their own Uncategorized and Opening balances),
-- payees and rules. A row that points at another row carries the same owner,
-- and its foreign key runs over (owner_principal_id, id), so a posting cannot
-- land on another owner's account or category, a transaction cannot name
-- another owner's payee, and a budget cannot be set on another owner's
-- category. Every uniqueness rule that is not already tied to one owner's row
-- is per owner.
--
-- Row level security narrows every statement to one owner. The store opens
-- each connection it works on for one owner by setting
-- budget_store.owner_principal_id (Store.OpenLedger); every policy below
-- compares the row's owner with it, and a new row's owner defaults to it. A
-- connection with the setting unset sees nothing and can write nothing: the
-- default fails, loudly. FORCE makes the policies hold for the module's own
-- role, which owns the tables. budget_store.reads_every_owner, set only in a
-- read-only transaction, lets the store find which owner keeps a record an
-- administrator asked for by its id (Store.ownerOfRecord).
--
-- Every numbered table has seq (its identity) and id (prefix + seq
-- zero-padded to six, account_000001), and a CHECK holds the id to the
-- number. Times are epoch seconds (0 = unset); dates are 'YYYY-MM-DD' text.
-- Text is collated "C", byte order, as SQLite compared it, so every ORDER BY,
-- MIN and MAX answers as it did, and upper() changes ASCII letters only, as
-- SQLite's did.

CREATE FUNCTION record_id(prefix text, number bigint) RETURNS text
    LANGUAGE sql IMMUTABLE STRICT
    RETURN prefix || '_' || CASE WHEN number < 1000000 THEN lpad(number::text, 6, '0') ELSE number::text END;

-- The owner the connection acts for. It errors when the connection was never
-- opened for an owner, so a row cannot be written without one.
CREATE FUNCTION acting_owner() RETURNS text
    LANGUAGE sql STABLE
    RETURN current_setting('budget_store.owner_principal_id');

CREATE DOMAIN owner_principal_id AS text COLLATE "C"
    CHECK (VALUE ~ '^principal_[0-9]{6,}$');

