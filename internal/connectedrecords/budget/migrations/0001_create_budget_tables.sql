-- Every transaction balances. The store refuses a write that would leave a
-- transaction's postings summing to anything but zero, or with fewer than
-- two; this checks the same at commit, so a fault in the store cannot leave
-- one behind. It is deferred because a write moves postings one at a time.
CREATE FUNCTION check_transaction_balances() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    checked_transaction_id text;
    posting_count bigint;
    posting_sum numeric;
BEGIN
    IF TG_TABLE_NAME = 'transactions' THEN
        checked_transaction_id := NEW.id;
    ELSIF TG_OP = 'DELETE' THEN
        checked_transaction_id := OLD.transaction_id;
    ELSE
        checked_transaction_id := NEW.transaction_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM transactions WHERE id = checked_transaction_id) THEN
        RETURN NULL; -- the transaction is gone, and its postings with it
    END IF;
    SELECT count(*), COALESCE(sum(amount_cents), 0) INTO posting_count, posting_sum
        FROM postings WHERE transaction_id = checked_transaction_id;
    IF posting_count < 2 OR posting_sum <> 0 THEN
        RAISE EXCEPTION 'transaction % does not balance: a transaction needs two or more postings summing to zero, and it has % postings', checked_transaction_id, posting_count
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER postings_balance AFTER INSERT OR UPDATE OR DELETE ON postings
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_transaction_balances();
CREATE CONSTRAINT TRIGGER transactions_balance AFTER INSERT ON transactions
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_transaction_balances();

-- An UPDATE that moves a posting to another transaction leaves the old one to
-- be checked as well.
CREATE FUNCTION check_transaction_left_balanced() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    posting_count bigint;
    posting_sum numeric;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM transactions WHERE id = OLD.transaction_id) THEN
        RETURN NULL;
    END IF;
    SELECT count(*), COALESCE(sum(amount_cents), 0) INTO posting_count, posting_sum
        FROM postings WHERE transaction_id = OLD.transaction_id;
    IF posting_count < 2 OR posting_sum <> 0 THEN
        RAISE EXCEPTION 'transaction % does not balance: a transaction needs two or more postings summing to zero, and it has % postings', OLD.transaction_id, posting_count
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER postings_leave_balance AFTER UPDATE OF transaction_id ON postings
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
    WHEN (OLD.transaction_id IS DISTINCT FROM NEW.transaction_id)
    EXECUTE FUNCTION check_transaction_left_balanced();

