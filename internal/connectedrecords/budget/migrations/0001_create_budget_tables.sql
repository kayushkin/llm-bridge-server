        'trip_transactions', 'interests', 'interest_rules', 'interest_history_sources', 'interest_transactions',
        'marketplace_orders', 'marketplace_order_lines', 'plaid_items', 'plaid_accounts'])
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', owned_table);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', owned_table);
        EXECUTE format($policy$CREATE POLICY one_owner ON %I
            USING (owner_principal_id = current_setting('budget_store.owner_principal_id', true))
            WITH CHECK (owner_principal_id = current_setting('budget_store.owner_principal_id', true))$policy$, owned_table);
        EXECUTE format($policy$CREATE POLICY finding_the_owner ON %I FOR SELECT
            USING (current_setting('budget_store.reads_every_owner', true) = 'on' AND current_setting('transaction_read_only') = 'on')$policy$, owned_table);
    END LOOP;
END $$;
