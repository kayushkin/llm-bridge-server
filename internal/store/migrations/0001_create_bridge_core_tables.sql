-- Where the session events of the bridge's SQLite events table end. Those
-- events stay in the archived bridge.db and are never copied here; the import
-- records the highest id that table handed out, so the session log numbers its
-- own events above every id a client may hold from it. One row, or none on a
-- server that never had a bridge.db.
CREATE TABLE archived_event_numbering (
    only_row                  bigint PRIMARY KEY CHECK (only_row = 1),
    highest_archived_event_id bigint NOT NULL CHECK (highest_archived_event_id >= 0),
    recorded_at               timestamptz NOT NULL,
    source_description        text COLLATE "C" NOT NULL
);
