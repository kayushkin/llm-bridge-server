-- The bridge's own records: sessions and everything kept about them, sign-in,
-- peers and their messages, settings, and the machines' readings. Each table is
-- the table of the same name the bridge kept in SQLite (bridge.db), with the
-- same columns, except events: session events live in the session_log module
-- only.
--
-- Text compares by bytes (COLLATE "C"), as it did in SQLite, so ids and names
-- sort as they always did. A SQLite DATETIME column is timestamptz here; a time
-- the bridge wrote into a TEXT column itself (RFC 3339) stays text. A SQLite
-- INTEGER that held 0 or 1 is boolean. An AUTOINCREMENT id is an identity
-- column, generated by default so the import can copy each row with its number.

CREATE TABLE sessions (
    bridge_id                  text COLLATE "C" PRIMARY KEY,
    session_id                 text COLLATE "C" NOT NULL DEFAULT '',
    harness_session_id         text COLLATE "C" NOT NULL DEFAULT '',
    display_name               text COLLATE "C" NOT NULL DEFAULT '',
    harness                    text COLLATE "C" NOT NULL,
    state                      text COLLATE "C" NOT NULL,
    pid                        bigint NOT NULL DEFAULT 0,
    agent_id                   text COLLATE "C" NOT NULL DEFAULT '',
    parent_id                  text COLLATE "C" NOT NULL DEFAULT '',
    instance_id                text COLLATE "C" NOT NULL DEFAULT '',
    created_at                 timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now(),
    forked_from_session_id     text COLLATE "C" NOT NULL DEFAULT '',
    manager_session_id         text COLLATE "C" NOT NULL DEFAULT '',
    root_session_id            text COLLATE "C" NOT NULL DEFAULT '',
    depth                      bigint NOT NULL DEFAULT 0,
    controlled_by              text COLLATE "C" NOT NULL DEFAULT '',
    refreshed_from_session_id  text COLLATE "C" NOT NULL DEFAULT '',
    working_dir                text COLLATE "C" NOT NULL DEFAULT '',
    principal_id               text COLLATE "C" NOT NULL DEFAULT '',
    bundle_id                  text COLLATE "C" NOT NULL DEFAULT '',
    card_id                    text COLLATE "C" NOT NULL DEFAULT '',
    harness_config             text COLLATE "C" NOT NULL DEFAULT '',
    info                       text COLLATE "C" NOT NULL DEFAULT '',
    folder_name                text COLLATE "C" NOT NULL DEFAULT '',
    purpose                    text COLLATE "C" NOT NULL DEFAULT '',
    -- The session's whole msg.SessionStatus as JSON; state is one field of it,
    -- kept as a column for the queries that filter on it. Written together.
    status                     text COLLATE "C" NOT NULL DEFAULT '',
    display_name_autogenerated boolean NOT NULL DEFAULT true,
    display_name_named_at_turn bigint NOT NULL DEFAULT 0,
    renamer_session_id         text COLLATE "C" NOT NULL DEFAULT '',
    mode                       text COLLATE "C" NOT NULL DEFAULT '',
    type                       text COLLATE "C" NOT NULL DEFAULT '',
    origin                     text COLLATE "C" NOT NULL DEFAULT '',
    max_budget_usd             double precision NOT NULL DEFAULT 0,
    spend_usd                  double precision NOT NULL DEFAULT 0,
    api_spend_detail           text COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX idx_sessions_state ON sessions (state);
CREATE INDEX idx_sessions_harness ON sessions (harness);
CREATE INDEX idx_sessions_manager ON sessions (manager_session_id) WHERE manager_session_id <> '';
CREATE INDEX idx_sessions_summary_session_id ON sessions ((COALESCE(NULLIF(session_id, ''), bridge_id)));
CREATE INDEX idx_sessions_purpose ON sessions (purpose);
CREATE UNIQUE INDEX idx_sessions_harness_session_id ON sessions (harness_session_id) WHERE harness_session_id <> '';
CREATE INDEX idx_sessions_folder ON sessions (folder_name);
