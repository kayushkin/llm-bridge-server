-- Rules, their immutable revisions, every activate/pause/retire, rule-store's
-- copy of each subject, and every decision a rule made. Times are Unix
-- seconds, as the API has always served them.

-- Every record's public id is its type's prefix and the number seq holds
-- (rule_000001, rule_run_000042). seq is an identity column: the store takes
-- the next number from its sequence before it writes the id, so two writers
-- never take the same one.
CREATE TABLE rules (
    id                 text PRIMARY KEY,
    seq                bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    name               text NOT NULL,
    description        text NOT NULL DEFAULT '',
    source             text NOT NULL,
    state              text NOT NULL,
    active_revision_id text NOT NULL DEFAULT '',
    mode               text NOT NULL DEFAULT '',
    created_by         text NOT NULL,
    created_at         bigint NOT NULL,
    updated_at         bigint NOT NULL
);

CREATE TABLE rule_revisions (
    id         text PRIMARY KEY,
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    rule_id    text NOT NULL REFERENCES rules (id),
    revision   integer NOT NULL,
    -- The definition as JSON, validated on write and kept as written.
    definition text NOT NULL,
    note       text NOT NULL DEFAULT '',
    created_by text NOT NULL,
    created_at bigint NOT NULL,
    UNIQUE (rule_id, revision)
);

CREATE TABLE rule_activations (
    id          text PRIMARY KEY,
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    rule_id     text NOT NULL REFERENCES rules (id),
    action      text NOT NULL,
    revision_id text NOT NULL DEFAULT '',
    mode        text NOT NULL DEFAULT '',
    acted_by    text NOT NULL,
    reason      text NOT NULL DEFAULT '',
    acted_at    bigint NOT NULL
);
CREATE INDEX rule_activations_rule ON rule_activations (rule_id, seq);

-- snapshot is the source's JSON verbatim, so it is text and not jsonb, which
-- would reorder its keys.
CREATE TABLE subjects (
    subject_type      text NOT NULL,
    subject_id        text NOT NULL,
    state             text NOT NULL,
    state_episode     bigint NOT NULL,
    state_observed_at bigint NOT NULL,
    snapshot          text NOT NULL,
    observed_at       bigint NOT NULL,
    PRIMARY KEY (subject_type, subject_id)
);
CREATE INDEX subjects_state ON subjects (subject_type, state);

CREATE TABLE rule_runs (
    id               text PRIMARY KEY,
    seq              bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    rule_id          text NOT NULL REFERENCES rules (id),
    rule_revision_id text NOT NULL REFERENCES rule_revisions (id),
    subject_type     text NOT NULL,
    subject_id       text NOT NULL,
    trigger_key      text NOT NULL,
    mode             text NOT NULL,
    cause            text NOT NULL,
    facts            text NOT NULL,
    planned_effects  text NOT NULL,
    outcome          text NOT NULL,
    decided_at       bigint NOT NULL,
    -- A revision decides once each time a subject enters a state.
    CONSTRAINT rule_runs_one_decision_per_state_entry UNIQUE (rule_revision_id, subject_type, subject_id, trigger_key)
);
CREATE INDEX rule_runs_rule ON rule_runs (rule_id, seq);
CREATE INDEX rule_runs_subject ON rule_runs (subject_type, subject_id);
