-- The model registry: providers, models, aliases, roles and each model's
-- health. Text keys sort byte by byte (COLLATE "C"), as SQLite's BINARY did.
--
-- listed_order keeps the order rows were first written in, which is the order
-- the standalone store's SQLite file listed providers and a model's aliases
-- in (its rowid). An import copies rows in that order, so lists come out as
-- they did.

CREATE TABLE providers (
	id           text COLLATE "C" PRIMARY KEY,
	name         text NOT NULL,
	-- Kept from the standalone file and read by nothing in this store.
	base_url     text,
	auth_type    text NOT NULL DEFAULT 'api_key',
	listed_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE models (
	id          text COLLATE "C" PRIMARY KEY,
	provider    text COLLATE "C" NOT NULL REFERENCES providers (id),
	name        text NOT NULL,
	short_name  text NOT NULL DEFAULT '',
	max_tokens  integer NOT NULL DEFAULT 200000,
	input_cost  double precision NOT NULL DEFAULT 0,
	output_cost double precision NOT NULL DEFAULT 0,
	enabled     boolean NOT NULL DEFAULT true,
	priority    integer NOT NULL DEFAULT 100
);

CREATE TABLE model_aliases (
	alias        text COLLATE "C" PRIMARY KEY,
	model_id     text COLLATE "C" NOT NULL REFERENCES models (id),
	listed_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX model_aliases_model_id ON model_aliases (model_id);

CREATE TABLE model_roles (
	role     text COLLATE "C" PRIMARY KEY,
	model_id text COLLATE "C" NOT NULL REFERENCES models (id)
);

CREATE TABLE model_role_fallbacks (
	role     text COLLATE "C" NOT NULL REFERENCES model_roles (role),
	position integer NOT NULL,
	model_id text COLLATE "C" NOT NULL REFERENCES models (id),
	PRIMARY KEY (role, position),
	UNIQUE (role, model_id)
);

-- Health is keyed by the name a caller recorded it under, which need not be a
-- model in the registry, so it has no foreign key. Times are unix seconds, and
-- 0 means never.
CREATE TABLE model_health (
	model              text COLLATE "C" PRIMARY KEY,
	last_success_at    bigint NOT NULL DEFAULT 0,
	last_success_ms    bigint NOT NULL DEFAULT 0,
	avg_response_ms    bigint NOT NULL DEFAULT 0,
	last_error_at      bigint NOT NULL DEFAULT 0,
	last_error         text NOT NULL DEFAULT '',
	consecutive_errors integer NOT NULL DEFAULT 0
);

-- Daily token counts an older orchestrator wrote into the standalone file.
-- Nothing in this store writes or reads them; the import keeps them so no
-- record is lost.
CREATE TABLE usage (
	date          text NOT NULL,
	agent         text NOT NULL,
	orchestrator  text NOT NULL DEFAULT 'inber',
	model         text NOT NULL,
	provider      text NOT NULL,
	input_tokens  bigint NOT NULL DEFAULT 0,
	output_tokens bigint NOT NULL DEFAULT 0,
	requests      bigint NOT NULL DEFAULT 0,
	cost_usd      double precision NOT NULL DEFAULT 0,
	PRIMARY KEY (date, agent, orchestrator, model)
);
