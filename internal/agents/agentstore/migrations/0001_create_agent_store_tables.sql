-- agent-store: agent identity, nature and harness configs, the tracked agent
-- and prompt files with every version of each, and the prompt source.
--
-- The tables, columns and constraints are those of the standalone SQLite
-- store once its own start-up migrations had run, so its file imports row for
-- row. SQLite's INTEGER is BIGINT here and flags stay 0 or 1, BLOB is BYTEA,
-- and every TEXT column sorts and compares byte by byte (COLLATE "C"), as
-- SQLite's BINARY collation did: the prompt a session receives is assembled
-- from ORDER BY on these columns, and a locale's order would change it.
-- Integer ids come from identity columns, BY DEFAULT so the import can keep
-- the ids that dash, sessions and drift rows already carry.

-- ============================================
-- AGENTS
-- ============================================

CREATE TABLE agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT COLLATE "C" UNIQUE NOT NULL,
    display_name TEXT COLLATE "C" NOT NULL,
    emoji TEXT COLLATE "C",
    projects TEXT COLLATE "C",              -- comma-separated: "si,dash"
    description TEXT COLLATE "C",
    role TEXT COLLATE "C",
    enabled BIGINT DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    workspace TEXT COLLATE "C" DEFAULT '',  -- written by an older store; nothing here reads it
    parent_agent_id BIGINT REFERENCES agents(id) ON DELETE SET NULL
);
CREATE INDEX idx_agents_parent ON agents(parent_agent_id);

-- The registry of agent runtimes (Claude Code, Codex, inber, …).
CREATE TABLE harness (
    id TEXT COLLATE "C" PRIMARY KEY,
    display_name TEXT COLLATE "C" NOT NULL,
    default_agent_id BIGINT REFERENCES agents(id) ON DELETE SET NULL,
    config_path TEXT COLLATE "C",
    api_endpoint TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    emoji TEXT COLLATE "C" DEFAULT ''
);

-- One agent's config on one harness.
CREATE TABLE agent_harness (
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    harness_id TEXT COLLATE "C" NOT NULL REFERENCES harness(id) ON DELETE CASCADE,
    harness_agent_id TEXT COLLATE "C" NOT NULL,   -- what the harness calls this agent
    enabled BIGINT DEFAULT 1,
    model_primary TEXT COLLATE "C",
    model_fallbacks TEXT COLLATE "C",              -- JSON array
    workspace_path TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    thinking_budget BIGINT DEFAULT 0,
    context_budget BIGINT DEFAULT 0,
    context_tags TEXT COLLATE "C",                 -- JSON array
    max_turns BIGINT DEFAULT 0,
    max_input_tokens BIGINT DEFAULT 0,
    max_response_time BIGINT DEFAULT 0,            -- seconds
    system_prompt TEXT COLLATE "C",
    project TEXT COLLATE "C",
    shelved BIGINT DEFAULT 0,
    is_default BIGINT DEFAULT 0,
    subagent_allow TEXT COLLATE "C",               -- JSON array, e.g. '["*"]'
    PRIMARY KEY (agent_id, harness_id)
);
CREATE INDEX idx_agent_harness_harness ON agent_harness(harness_id);

CREATE TABLE agent_harness_tools (
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    harness_id TEXT COLLATE "C" NOT NULL REFERENCES harness(id) ON DELETE CASCADE,
    tool_name TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (agent_id, harness_id, tool_name)
);

CREATE TABLE agent_skills (
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    skill_id TEXT COLLATE "C" NOT NULL,            -- a skill-store entry's id
    PRIMARY KEY (agent_id, skill_id)
);

CREATE TABLE agent_system_prompt_refs (
    harness_id TEXT COLLATE "C" NOT NULL REFERENCES harness(id) ON DELETE CASCADE,
    host_agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    referenced_agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    prompt_location TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (harness_id, host_agent_id, referenced_agent_id, prompt_location)
);

CREATE TABLE agent_nature (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    kind TEXT COLLATE "C" NOT NULL,                -- identity, principle, value, user, project
    content TEXT COLLATE "C" NOT NULL,
    content_hash TEXT COLLATE "C",
    priority BIGINT DEFAULT 0,
    source_path TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX idx_agent_nature_agent ON agent_nature(agent_id);
CREATE INDEX idx_agent_nature_kind ON agent_nature(kind);

CREATE TABLE agent_name_aliases (
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    alias TEXT COLLATE "C" NOT NULL,
    context TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    PRIMARY KEY (agent_id, alias)
);
CREATE INDEX idx_aliases_alias ON agent_name_aliases(alias);

CREATE TABLE file_distributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    harness_id TEXT COLLATE "C" NOT NULL REFERENCES harness(id) ON DELETE CASCADE,
    file_path TEXT COLLATE "C" NOT NULL,
    content_hash TEXT COLLATE "C" NOT NULL,
    distributed_at BIGINT NOT NULL,
    source_nature_ids TEXT COLLATE "C"             -- JSON array of agent_nature ids
);
CREATE INDEX idx_file_dist_agent ON file_distributions(agent_id);
CREATE INDEX idx_file_dist_harness ON file_distributions(harness_id);
CREATE INDEX idx_file_dist_path ON file_distributions(file_path);

CREATE TABLE file_scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_distribution_id BIGINT NOT NULL REFERENCES file_distributions(id) ON DELETE CASCADE,
    scanned_at BIGINT NOT NULL,
    current_hash TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL,              -- unchanged, modified, missing, new
    diff_summary TEXT COLLATE "C",
    ingested BIGINT DEFAULT 0
);
CREATE INDEX idx_file_scans_dist ON file_scans(file_distribution_id);
CREATE INDEX idx_file_scans_status ON file_scans(status);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT COLLATE "C" UNIQUE NOT NULL,
    name TEXT COLLATE "C" NOT NULL,
    path TEXT COLLATE "C",
    description TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE project_nature (
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    nature_id BIGINT NOT NULL REFERENCES agent_nature(id) ON DELETE CASCADE,
    priority BIGINT DEFAULT 0,
    PRIMARY KEY (project_id, nature_id)
);

CREATE TABLE agent_status (
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    harness_id TEXT COLLATE "C" NOT NULL REFERENCES harness(id) ON DELETE CASCADE,
    status TEXT COLLATE "C" NOT NULL DEFAULT 'idle',
    task TEXT COLLATE "C",
    session_id TEXT COLLATE "C",
    started_at BIGINT,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (agent_id, harness_id)
);

-- ============================================
-- TRACKED FILES and every version of each
-- ============================================
-- path is the canonical path, without a .disabled suffix; enabled = 0 means
-- the file lives at path + ".disabled". The row holds no content: GET
-- /files/{id}/content reads the disk.

CREATE TABLE tracked_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path TEXT COLLATE "C" UNIQUE NOT NULL,
    scope TEXT COLLATE "C" NOT NULL,
    agent_slug TEXT COLLATE "C",
    enabled BIGINT NOT NULL DEFAULT 1,
    fs_hash TEXT COLLATE "C",
    size BIGINT,
    mtime BIGINT,
    last_scanned_at BIGINT,
    status TEXT COLLATE "C" NOT NULL DEFAULT 'present',  -- present, missing
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    ignored_by_rule_id BIGINT                    -- tracked_file_ignore_rules.id; NULL = not ignored
);
CREATE INDEX idx_tracked_files_scope ON tracked_files(scope);
CREATE INDEX idx_tracked_files_agent ON tracked_files(agent_slug);
CREATE INDEX idx_tracked_files_status ON tracked_files(status);

-- Every UI save, scan-detected change and runner-reported drift is a row, kept
-- forever. source: ui-save, scan-import, runner-drift, seed, harness-render.
CREATE TABLE tracked_file_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracked_file_id BIGINT NOT NULL REFERENCES tracked_files(id) ON DELETE CASCADE,
    sha256 TEXT COLLATE "C" NOT NULL,
    size BIGINT NOT NULL,
    content_bytes BYTEA NOT NULL,
    source TEXT COLLATE "C" NOT NULL,
    machine_id TEXT COLLATE "C",
    note TEXT COLLATE "C",
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_tracked_file_versions_file ON tracked_file_versions(tracked_file_id, created_at DESC);
CREATE INDEX idx_tracked_file_versions_sha ON tracked_file_versions(tracked_file_id, sha256);

-- Paths the scan finds but that are copies or third-party files. A matching
-- row is stamped, never deleted.
CREATE TABLE tracked_file_ignore_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT COLLATE "C" NOT NULL,                -- path_pattern, git_worktree
    path_pattern TEXT COLLATE "C" NOT NULL DEFAULT '',
    reason TEXT COLLATE "C" NOT NULL,
    enabled BIGINT NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    UNIQUE (kind, path_pattern)
);

-- One row per runner machine: the scopes it pulls down, as a JSON array.
CREATE TABLE machine_seed_profiles (
    machine_id TEXT COLLATE "C" PRIMARY KEY,
    scopes TEXT COLLATE "C" NOT NULL DEFAULT '["global","subagent","memory","command","inber"]',
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

-- What hash a runner last reported for a tracked file, and what was last
-- pushed to it.
CREATE TABLE machine_seed_state (
    machine_id TEXT COLLATE "C" NOT NULL,
    tracked_file_id BIGINT NOT NULL REFERENCES tracked_files(id) ON DELETE CASCADE,
    observed_sha TEXT COLLATE "C",
    observed_at BIGINT,
    last_pushed_version_id BIGINT REFERENCES tracked_file_versions(id) ON DELETE SET NULL,
    last_pushed_at BIGINT,
    PRIMARY KEY (machine_id, tracked_file_id)
);
CREATE INDEX idx_machine_seed_state_machine ON machine_seed_state(machine_id);

-- ============================================
-- THE PROMPT SOURCE
-- ============================================
-- The prompt is stored as sections, and a section names no harness and no
-- file. Which files a collection renders to is prompt_collection_outputs;
-- how a harness gets the prompt is prompt_harness_deliveries.

CREATE TABLE prompt_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT COLLATE "C" UNIQUE NOT NULL,
    title TEXT COLLATE "C" NOT NULL,
    scope TEXT COLLATE "C" NOT NULL,               -- global, project, context
    root_path TEXT COLLATE "C" NOT NULL,
    description TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    retired_at BIGINT NOT NULL DEFAULT 0           -- RetirePromptCollection; 0 while in use
);
CREATE UNIQUE INDEX idx_prompt_collections_scope_root ON prompt_collections(scope, root_path);

-- The first splitter's sections, each tied to a file by applies_to. Set
-- aside, not dropped: nothing reads them.
CREATE TABLE prompt_sections_legacy_per_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES prompt_collections(id) ON DELETE CASCADE,
    title TEXT COLLATE "C" NOT NULL,
    heading TEXT COLLATE "C",
    body TEXT COLLATE "C" NOT NULL,
    applies_to TEXT COLLATE "C" NOT NULL,          -- all, claude, agents
    priority BIGINT NOT NULL DEFAULT 0,
    enabled BIGINT NOT NULL DEFAULT 1,
    source_path TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE prompt_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES prompt_collections(id) ON DELETE CASCADE,
    title TEXT COLLATE "C" NOT NULL,
    heading TEXT COLLATE "C" NOT NULL DEFAULT '',  -- the markdown heading line, '' for a preamble
    body TEXT COLLATE "C" NOT NULL,
    tags TEXT COLLATE "C" NOT NULL DEFAULT '[]',   -- JSON array of strings
    position BIGINT NOT NULL DEFAULT 0,            -- render order within the collection
    enabled BIGINT NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX idx_prompt_sections_collection_position ON prompt_sections(collection_id, position, id);

-- Append-only: one row per write to a section, holding the state it left (for
-- a delete, the state it removed). No foreign key, so the history of a deleted
-- section survives it.
CREATE TABLE prompt_section_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL,
    collection_id BIGINT NOT NULL,
    operation TEXT COLLATE "C" NOT NULL,           -- create, update, delete
    title TEXT COLLATE "C" NOT NULL,
    heading TEXT COLLATE "C" NOT NULL,
    body TEXT COLLATE "C" NOT NULL,
    tags TEXT COLLATE "C" NOT NULL,
    position BIGINT NOT NULL,
    enabled BIGINT NOT NULL,
    source TEXT COLLATE "C" NOT NULL,              -- import, ui, drift
    drift_id BIGINT,                               -- prompt_drifts.id when source = drift
    note TEXT COLLATE "C",
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_prompt_section_revisions_section ON prompt_section_revisions(section_id, id);
CREATE INDEX idx_prompt_section_revisions_collection ON prompt_section_revisions(collection_id, id);

-- A file one collection renders to. accounted_sha256 is the hash of the last
-- disk content the sections account for; a disk hash that differs is drift,
-- and a render refuses to write over drift.
CREATE TABLE prompt_collection_outputs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES prompt_collections(id) ON DELETE CASCADE,
    relative_path TEXT COLLATE "C" NOT NULL,
    enabled BIGINT NOT NULL DEFAULT 1,
    accounted_sha256 TEXT COLLATE "C",
    accounted_at BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE (collection_id, relative_path)
);

-- How the bridge hands the prompt to one harness: inject, or native_file
-- when the harness reads a rendered file itself.
CREATE TABLE prompt_harness_deliveries (
    harness TEXT COLLATE "C" PRIMARY KEY,
    delivery TEXT COLLATE "C" NOT NULL,
    native_relative_path TEXT COLLATE "C",
    note TEXT COLLATE "C",
    updated_at BIGINT NOT NULL
);

-- An output whose disk content no longer matches what the sections account
-- for. disk_content keeps the edit whatever happens to the file next.
CREATE TABLE prompt_drifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES prompt_collections(id) ON DELETE CASCADE,
    output_id BIGINT NOT NULL REFERENCES prompt_collection_outputs(id) ON DELETE CASCADE,
    accounted_sha256 TEXT COLLATE "C",
    disk_sha256 TEXT COLLATE "C" NOT NULL,
    disk_content BYTEA NOT NULL,
    status TEXT COLLATE "C" NOT NULL,              -- open, held, applied, dismissed, superseded
    held_reason TEXT COLLATE "C",
    operations TEXT COLLATE "C",                   -- JSON
    annotation TEXT COLLATE "C",                   -- JSON
    created_at BIGINT NOT NULL,
    resolved_at BIGINT,
    UNIQUE (output_id, disk_sha256)
);
CREATE INDEX idx_prompt_drifts_status ON prompt_drifts(status, id);
