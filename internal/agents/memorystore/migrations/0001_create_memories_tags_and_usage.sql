-- The schema the standalone SQLite store ended at, after every migration in
-- its old runMigrations: memories with their tags and the record of which
-- session used which memory. Times are Unix seconds, as they were, and the
-- embedding is the JSON text of the vector, kept as the bytes the store wrote.

-- Search reads text the way the SQLite store's FTS5 index did with
-- tokenize='porter unicode61': every word is stemmed and none is dropped. The
-- built-in english configuration drops stop words, which would change how
-- many words a memory holds and so its BM25 weight; this one stems with the
-- same Snowball stemmer and keeps every word. The Go side drops stop words
-- from a query, as it did before.
CREATE TEXT SEARCH DICTIONARY memory_stem (TEMPLATE = pg_catalog.snowball, Language = english);
CREATE TEXT SEARCH CONFIGURATION memory_text (COPY = pg_catalog.simple);
ALTER TEXT SEARCH CONFIGURATION memory_text
    ALTER MAPPING FOR asciiword, word, numword, asciihword, hword, numhword,
                      hword_asciipart, hword_part, hword_numpart
    WITH memory_stem;

-- How many words a search document holds: the sum of each lexeme's positions.
-- BM25 weighs a match by the length of the memory it is in.
CREATE FUNCTION count_words_of(document tsvector) RETURNS integer
    LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
    RETURN (SELECT coalesce(sum(cardinality(entry.positions)), 0)::integer FROM unnest(document) AS entry);

CREATE TABLE memories (
    id              text PRIMARY KEY,
    content         text NOT NULL,
    summary         text,
    original_id     text,
    importance      double precision NOT NULL DEFAULT 0.5,
    access_count    bigint NOT NULL DEFAULT 0,
    last_accessed   bigint NOT NULL,
    created_at      bigint NOT NULL,
    source          text NOT NULL,
    embedding       bytea,
    always_load     boolean NOT NULL DEFAULT false,
    expires_at      bigint,
    tokens          bigint NOT NULL DEFAULT 0,
    ref_type        text NOT NULL DEFAULT 'memory',
    ref_target      text,
    is_lazy         boolean NOT NULL DEFAULT false,
    orchestrator    text NOT NULL DEFAULT '',
    -- What Search ranks: the content and the summary, split into words as the
    -- FTS5 unicode61 tokenizer split them. Every ASCII punctuation mark
    -- separates words, so timeout_seconds is "timeout seconds" and
    -- auth-store is "auth store"; without the translate, Postgres keeps paths,
    -- file names and hyphenated words as tokens of their own.
    search_document tsvector GENERATED ALWAYS AS (
        to_tsvector('memory_text'::regconfig, translate(
            content || ' ' || coalesce(summary, ''),
            '!"#$%&''()*+,-./:;<=>?@[\]^_`{|}~', '                                '))
    ) STORED,
    search_word_count integer GENERATED ALWAYS AS (
        count_words_of(to_tsvector('memory_text'::regconfig, translate(
            content || ' ' || coalesce(summary, ''),
            '!"#$%&''()*+,-./:;<=>?@[\]^_`{|}~', '                                ')))
    ) STORED
);
CREATE INDEX memories_importance_index    ON memories (importance);
CREATE INDEX memories_last_accessed_index ON memories (last_accessed);
CREATE INDEX memories_created_at_index    ON memories (created_at);
CREATE INDEX memories_source_index        ON memories (source);
CREATE INDEX memories_always_load_index   ON memories (always_load);
CREATE INDEX memories_expires_at_index    ON memories (expires_at);
CREATE INDEX memories_ref_type_index      ON memories (ref_type);
CREATE INDEX memories_orchestrator_index  ON memories (orchestrator);
CREATE INDEX memories_search_index        ON memories USING gin (search_document);

-- A memory's tags, as many rows as tags. Save replaces them all at once.
-- insertion_order keeps them in the order they were written, which SQLite gave
-- by its rowid.
CREATE TABLE memory_tags (
    insertion_order bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    memory_id       text NOT NULL REFERENCES memories (id) ON DELETE CASCADE,
    tag             text NOT NULL
);
CREATE INDEX memory_tags_memory_id_index ON memory_tags (memory_id);
CREATE INDEX memory_tags_tag_index       ON memory_tags (tag);

-- When a session used a memory. session_id is the bridge's session id, an
-- opaque reference: the store keeps no sessions of its own.
CREATE TABLE memory_usage (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    memory_id   text NOT NULL REFERENCES memories (id) ON DELETE CASCADE,
    session_id  text NOT NULL,
    turn_number bigint NOT NULL,
    usage_type  text NOT NULL,
    accessed_at bigint NOT NULL
);
CREATE INDEX memory_usage_memory_id_index  ON memory_usage (memory_id);
CREATE INDEX memory_usage_session_id_index ON memory_usage (session_id);
