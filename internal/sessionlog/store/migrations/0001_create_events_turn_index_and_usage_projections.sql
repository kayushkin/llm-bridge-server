-- The session event log: every event of every session, and the tables derived
-- from it. events is the record; every other table is derived and can be
-- emptied and rebuilt from it.
--
-- Session ids and query sources sort and compare by bytes (COLLATE "C"), as
-- they did in SQLite, so every ordered answer comes out in the same order.

-- One row per event, stored as the writer sent it: the json type keeps the
-- text exactly as given, and checks only that it is JSON.
CREATE TABLE events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text COLLATE "C" NOT NULL,
    type       text NOT NULL,
    data       json NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX events_session_id ON events (session_id, id);
CREATE INDEX events_session_type_id ON events (session_id, type, id);

-- Per-session totals, added to by each new event.
CREATE TABLE sessions (
    session_id         text COLLATE "C" PRIMARY KEY,
    turn_count         bigint NOT NULL DEFAULT 0,
    input_tokens       bigint NOT NULL DEFAULT 0,
    output_tokens      bigint NOT NULL DEFAULT 0,
    cache_read_tokens  bigint NOT NULL DEFAULT 0,
    cache_write_tokens bigint NOT NULL DEFAULT 0,
    duration_ms        bigint NOT NULL DEFAULT 0,
    model              text NOT NULL DEFAULT '',
    harness_session_id text NOT NULL DEFAULT '',
    started_at         timestamptz NOT NULL DEFAULT now(),
    last_active        timestamptz NOT NULL DEFAULT now(),
    ended_at           timestamptz
);
CREATE INDEX sessions_last_active ON sessions (last_active);
CREATE INDEX sessions_harness_session_id ON sessions (harness_session_id) WHERE harness_session_id <> '';

-- The api_call events summed per session and query source.
CREATE TABLE session_api_call_usage (
    session_id         text COLLATE "C" NOT NULL,
    query_source       text COLLATE "C" NOT NULL,
    calls              bigint NOT NULL DEFAULT 0,
    input_tokens       bigint NOT NULL DEFAULT 0,
    output_tokens      bigint NOT NULL DEFAULT 0,
    cache_read_tokens  bigint NOT NULL DEFAULT 0,
    cache_write_tokens bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (session_id, query_source)
);

-- The same counts per session and clock hour (the unix time the hour began).
CREATE TABLE session_usage_by_hour (
    session_id             text COLLATE "C" NOT NULL,
    hour_start_unix        bigint NOT NULL,
    turn_count             bigint NOT NULL DEFAULT 0,
    input_tokens           bigint NOT NULL DEFAULT 0,
    output_tokens          bigint NOT NULL DEFAULT 0,
    cache_read_tokens      bigint NOT NULL DEFAULT 0,
    cache_write_tokens     bigint NOT NULL DEFAULT 0,
    duration_ms            bigint NOT NULL DEFAULT 0,
    session_cost_total_usd double precision,
    PRIMARY KEY (session_id, hour_start_unix)
);
CREATE INDEX session_usage_by_hour_hour ON session_usage_by_hour (hour_start_unix);

CREATE TABLE session_api_call_usage_by_hour (
    session_id         text COLLATE "C" NOT NULL,
    hour_start_unix    bigint NOT NULL,
    query_source       text COLLATE "C" NOT NULL,
    calls              bigint NOT NULL DEFAULT 0,
    input_tokens       bigint NOT NULL DEFAULT 0,
    output_tokens      bigint NOT NULL DEFAULT 0,
    cache_read_tokens  bigint NOT NULL DEFAULT 0,
    cache_write_tokens bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (session_id, hour_start_unix, query_source)
);
CREATE INDEX session_api_call_usage_by_hour_hour ON session_api_call_usage_by_hour (hour_start_unix);

-- The turn index and the stored turn model; see turn_index.go.
CREATE TABLE turn_index_sessions (
    session_id               text COLLATE "C" PRIMARY KEY,
    index_version            integer NOT NULL,
    indexed_through_event_id bigint NOT NULL,
    last_turn_id             text NOT NULL,
    next_turn_seq            bigint NOT NULL
);

CREATE TABLE event_turns (
    event_id   bigint PRIMARY KEY,
    session_id text COLLATE "C" NOT NULL,
    turn_seq   bigint NOT NULL
);
CREATE INDEX event_turns_session_turn ON event_turns (session_id, turn_seq, event_id);

CREATE TABLE turns (
    session_id                    text COLLATE "C" NOT NULL,
    turn_seq                      bigint NOT NULL,
    turn_id                       text NOT NULL,
    first_event_id                bigint NOT NULL,
    last_event_id                 bigint NOT NULL,
    event_count                   bigint NOT NULL,
    has_user_message              boolean NOT NULL DEFAULT false,
    materializer_version          integer NOT NULL DEFAULT 0,
    materialized_through_event_id bigint NOT NULL DEFAULT 0,
    turn_json                     text NOT NULL DEFAULT '',
    source_groups_json            text NOT NULL DEFAULT '',
    aggregate_sources_json        text NOT NULL DEFAULT '',
    dedup_fingerprint             text NOT NULL DEFAULT '',
    PRIMARY KEY (session_id, turn_seq)
);
CREATE UNIQUE INDEX turns_session_turn_id ON turns (session_id, turn_id);
CREATE INDEX turns_session_prompt ON turns (session_id, has_user_message, turn_seq);

CREATE TABLE turn_entries (
    session_id text COLLATE "C" NOT NULL,
    turn_seq   bigint NOT NULL,
    event_id   bigint NOT NULL,
    entry_json text NOT NULL,
    PRIMARY KEY (session_id, turn_seq, event_id)
);

CREATE TABLE dedup_candidates (
    event_id   bigint PRIMARY KEY,
    session_id text COLLATE "C" NOT NULL,
    turn_seq   bigint NOT NULL,
    key_hash   text NOT NULL,
    source     text NOT NULL
);
CREATE INDEX dedup_candidates_session ON dedup_candidates (session_id, event_id);

-- json_number reads a JSON value as a number, and anything that is not a
-- JSON number as NULL, which a sum skips. SQLite's json_extract summed the
-- same way.
CREATE FUNCTION json_number(value json) RETURNS numeric
    LANGUAGE sql IMMUTABLE
    RETURN CASE WHEN json_typeof(value) = 'number' THEN (value #>> '{}')::numeric END;
